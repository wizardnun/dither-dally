export const CELL_W = 6;
export const CELL_H = 8;

/** A glyph as a 6×8 ink mask (1 = ink), row-major. */
export type Glyph = Uint8Array;

/** Shading blocks fill the whole cell with an even pattern. */
function shade(level: 0 | 1 | 2 | 3): Glyph {
  const g = new Uint8Array(CELL_W * CELL_H);
  for (let y = 0; y < CELL_H; y++) {
    for (let x = 0; x < CELL_W; x++) {
      const on =
        level === 3 ||
        (level === 2 && !(x % 2 === 0 && y % 2 === 0)) || // 75%
        (level === 1 && (x + y) % 2 === 0) || // 50% checkerboard
        (level === 0 && x % 2 === 0 && y % 2 === 0); // 25%
      g[y * CELL_W + x] = on ? 1 : 0;
    }
  }
  return g;
}

const FONT = new Map<string, Glyph>();
for (const [ch, rows] of Object.entries(GLYPHS)) {
  const g = new Uint8Array(CELL_W * CELL_H);
  rows.split("|").forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === "#") g[y * CELL_W + x] = 1;
  });
  FONT.set(ch, g);
}
FONT.set("░", shade(0));
FONT.set("▒", shade(1));
FONT.set("▓", shade(2));
FONT.set("█", shade(3));

export function glyph(ch: string): Glyph | undefined {
  return FONT.get(ch);
}

/** Every character the font can draw. */
export const FONT_CHARS: readonly string[] = [...FONT.keys()];

/** Share of the cell that is ink, 0–1. */
export function coverage(g: Glyph): number {
  let n = 0;
  for (const v of g) n += v;
  return n / g.length;
}

/** Raw glyph definitions, exposed for tests. */
export const GLYPH_SOURCE: Readonly<Record<string, string>> = GLYPHS;
